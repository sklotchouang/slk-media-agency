// Copies the Podcast Toolkits product data and images from the product-forge handoff
// folder into this repo, converting every image to WebP at the sizes the shop uses.
// The handoff originals are only read, never changed.
//
//   node scripts/sync-toolkits.mjs
//
// Re-run it whenever products.json or an image in the handoff folder changes
// (for example once the bundle link or the outreach code is filled in).

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const HANDOFF = process.env.TOOLKITS_HANDOFF || 'D:/CLAUDE CODE/product-forge/website-handoff';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'public', 'podcast-toolkits', 'guides');
const DATA_OUT = path.join(ROOT, 'app', '(multiplier)', 'podcast-toolkits', 'toolkits.json');
const PUBLIC_BASE = '/podcast-toolkits/guides';

async function toWebp(src, dest, width, quality = 78) {
  await sharp(src).resize({ width, withoutEnlargement: true }).webp({ quality }).toFile(dest);
}

const data = JSON.parse(await readFile(path.join(HANDOFF, 'products.json'), 'utf8'));
await mkdir(OUT_DIR, { recursive: true });

const products = [];
for (const p of data.products) {
  const dir = path.join(OUT_DIR, p.id);
  await mkdir(dir, { recursive: true });
  const cover = path.join(HANDOFF, p.images.cover);
  await toWebp(cover, path.join(dir, 'cover-400.webp'), 400);
  await toWebp(cover, path.join(dir, 'cover-720.webp'), 720);
  const previews = [];
  for (const [i, rel] of p.images.previews.entries()) {
    const n = i + 1;
    const src = path.join(HANDOFF, rel);
    await toWebp(src, path.join(dir, `preview-${n}-900.webp`), 900, 80);
    await toWebp(src, path.join(dir, `preview-${n}-160.webp`), 160, 70);
    previews.push({
      full: `${PUBLIC_BASE}/${p.id}/preview-${n}-900.webp`,
      thumb: `${PUBLIC_BASE}/${p.id}/preview-${n}-160.webp`,
    });
  }
  const { images, ...rest } = p;
  products.push({
    ...rest,
    cover: {
      small: `${PUBLIC_BASE}/${p.id}/cover-400.webp`,
      large: `${PUBLIC_BASE}/${p.id}/cover-720.webp`,
    },
    previews,
  });
  console.log('synced', p.id);
}

const bundleDir = path.join(OUT_DIR, 'bundle');
await mkdir(bundleDir, { recursive: true });
await toWebp(path.join(HANDOFF, 'bundle', 'bundle-cover.png'), path.join(bundleDir, 'bundle-cover-960.webp'), 960);

const { products: _ignored, ...meta } = data;
const out = {
  _note: 'Generated by scripts/sync-toolkits.mjs from the product-forge handoff folder. Edit products.json there, then re-run the script.',
  ...meta,
  bundle: { ...data.bundle, image: `${PUBLIC_BASE}/bundle/bundle-cover-960.webp` },
  products,
};
await writeFile(DATA_OUT, JSON.stringify(out, null, 2) + '\n');
console.log('wrote', path.relative(ROOT, DATA_OUT));
